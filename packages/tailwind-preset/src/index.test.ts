/**
 * BLKC Tailwind Preset - Unit Tests
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import blkcPreset, {
  blkcTokens,
  blkcCssVariables,
  blkcThemeCss,
  resolveBlkcTheme,
  type BlkcThemeOverrides,
} from "./index";

describe("blkcTokens", () => {
  it("covers every token the renderer reads", () => {
    expect(blkcTokens["--blkc-color-primary"]).toBe("#0066cc");
    expect(blkcTokens["--blkc-color-border"]).toContain("color-mix");
    expect(blkcTokens["--blkc-max-width"]).toBe("1200px");
    expect(blkcTokens["--blkc-border-radius"]).toBe("8px");
  });
});

describe("resolveBlkcTheme", () => {
  it("returns the defaults when nothing is overridden", () => {
    expect(resolveBlkcTheme()).toEqual(blkcTokens);
  });

  it("keeps the remaining tokens when one is overridden", () => {
    const theme = resolveBlkcTheme({ "--blkc-color-primary": "#ff0000" });

    expect(theme["--blkc-color-primary"]).toBe("#ff0000");
    expect(theme["--blkc-color-text"]).toBe(blkcTokens["--blkc-color-text"]);
  });
});

describe("blkcCssVariables", () => {
  it("wraps declarations in the given selector", () => {
    const css = blkcCssVariables();

    expect(css.startsWith(":root {")).toBe(true);
    expect(css).toContain("  --blkc-color-primary: #0066cc;");
    expect(css.trimEnd().endsWith("}")).toBe(true);
  });

  it("applies overrides and honours a custom selector", () => {
    const overrides: BlkcThemeOverrides = { "--blkc-color-primary": "#123456" };
    const css = blkcCssVariables(overrides, ".kit-dark");

    expect(css.startsWith(".kit-dark {")).toBe(true);
    expect(css).toContain("--blkc-color-primary: #123456;");
    expect(css).not.toContain("#0066cc");
  });

  it("emits bare declarations for Tailwind v4 @theme blocks", () => {
    const css = blkcCssVariables({}, "");

    expect(css.trimStart().startsWith("--blkc-color-primary:")).toBe(true);
    expect(css).not.toContain("{");
  });
});

describe("blkcPreset", () => {
  it("maps semantic colours onto the CSS variables", () => {
    const colors = blkcPreset.theme.extend.colors;

    expect(colors["primary"]).toContain("--blkc-color-primary");
    expect(colors["foreground"]).toContain("--blkc-color-text");
    expect(colors["muted-foreground"]).toContain("--blkc-color-text-secondary");
    expect(colors["border"]).toContain("--blkc-color-border");
  });

  it("provides a fallback for every variable it reads", () => {
    const values = Object.values(blkcPreset.theme.extend).flatMap((group) =>
      Object.values(group).flat(),
    );

    for (const value of values) {
      if (value.includes("var(--")) {
        expect(value).toMatch(/var\(--[a-z-]+,/);
      }
    }
  });

  it("ships radius, width, font and spacing scales", () => {
    expect(blkcPreset.theme.extend.borderRadius["blkc"]).toContain("--blkc-border-radius");
    expect(blkcPreset.theme.extend.maxWidth["blkc"]).toContain("--blkc-max-width");
    expect(blkcPreset.theme.extend.fontFamily["blkc"]?.[0]).toContain("--blkc-font-family");
    expect(blkcPreset.theme.extend.spacing["blkc-md"]).toContain("--blkc-spacing-md");
  });
});

describe("blkcThemeCss", () => {
  it("declares the utilities the renderer emits", () => {
    const css = blkcThemeCss();

    expect(css.startsWith("@theme inline {")).toBe(true);
    for (const utility of [
      "--color-primary:",
      "--color-muted-foreground:",
      "--color-border:",
      "--radius-blkc:",
      "--container-blkc:",
      "--font-blkc:",
      "--spacing-blkc-md:",
    ]) {
      expect(css).toContain(utility);
    }
  });

  it("resolves through the CSS variable so overrides cascade", () => {
    expect(blkcThemeCss()).toContain(
      "--color-primary: var(--blkc-color-primary, #0066cc);",
    );
  });

  it("uses overridden values as fallbacks only", () => {
    const css = blkcThemeCss({ "--blkc-color-primary": "#ff0000" });

    expect(css).toContain("var(--blkc-color-primary, #ff0000)");
    expect(css).not.toContain("var(--blkc-color-primary, #0066cc)");
  });
});

describe("blkc.css", () => {
  it("is generated from the same tokens it ships", () => {
    const shipped = readFileSync(new URL("../blkc.css", import.meta.url), "utf8");
    const banner = "/* Generated by scripts/build-css.mjs - do not edit by hand. */";

    expect(shipped).toContain(banner);
    expect(shipped).toContain("@source");
    expect(shipped).toContain(blkcCssVariables().trim());
    expect(shipped).toContain(blkcThemeCss().trim());
  });
});
