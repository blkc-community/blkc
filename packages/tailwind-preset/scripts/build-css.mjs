/**
 * Generates src/blkc.css from the token map.
 *
 * The CSS file ships with the package for Tailwind v4 (`@import`) and for
 * projects that do not run the JS preset at all. It is generated rather than
 * hand-written so the two cannot drift; `src/index.test.ts` fails if it does.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { blkcCssVariables, blkcThemeCss } from "../dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "blkc.css");

const banner = `/* Generated by scripts/build-css.mjs - do not edit by hand. */
/*
 * Blocks live in @blkc-code/render-web, which Tailwind does not scan on its
 * own (node_modules is ignored by default). Without this the utilities the
 * renderer emits would never be generated.
 */
@source "../render-web/src";

`;
writeFileSync(target, banner + blkcCssVariables() + "\n" + blkcThemeCss());
console.log(`wrote ${target}`);
